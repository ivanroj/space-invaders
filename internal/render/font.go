type glyph struct {
	w, h int
	bits []bool
}

func compile(src map[rune]string, w, h int) map[rune]*glyph {
	out := make(map[rune]*glyph, len(src))
	for ch, s := range src {
		g := &glyph{w: w, h: h, bits: make([]bool, 0, w*h)}
		for _, c := range s {
			if c != '/' {
				g.bits = append(g.bits, c == '#')
			}
		}
		if len(g.bits) != w*h {
			panic("render: bad glyph " + string(ch))
		}
		out[ch] = g
	}
	return out
}

var (
	glyphs5 = compile(font5, 5, 7)
	glyphs3 = compile(font3, 3, 5)
)

func (r *Renderer) drawText(set map[rune]*glyph, adv int, s string, x, y int, c uint32, k int) {
	for _, ch := range s {
		if g := set[ch]; g != nil {
			for gy := 0; gy < g.h; gy++ {
				for gx := 0; gx < g.w; gx++ {
					if g.bits[gy*g.w+gx] {
						if k == 1 {
							r.set(x+gx, y+gy, c)
						} else {
							r.rect(x+gx*k, y+gy*k, k, k, c)
						}
					}
				}
			}
		}
		x += adv * k
	}
}

// text draws s in the 5x7 font, scaled by k.
func (r *Renderer) text(s string, x, y int, c uint32, k int) {
	r.drawText(glyphs5, 6, s, x, y, c, k)
}

// textC draws s centred on cx.
func (r *Renderer) textC(s string, cx, y int, c uint32, k int) {
	r.text(s, cx-textW(s, k)/2, y, c, k)
}

func textW(s string, k int) int { return (len(s)*6 - 1) * k }

// small draws s in the 3x5 font, centred on cx.
func (r *Renderer) small(s string, cx, y int, c uint32) {
	r.drawText(glyphs3, 4, s, cx-(len(s)*4-1)/2, y, c, 1)
}

// itoa formats n with at least width digits without allocating a format
// state: fmt would pull a megabyte of code into the wasm binary.
func itoa(n, width int) string {
	var buf [12]byte
	i := len(buf)
	for n > 0 || i == len(buf) {
		i--
		buf[i] = byte('0' + n%10)
		n /= 10
	}
	for len(buf)-i < width {
		i--
		buf[i] = '0'
	}
	return string(buf[i:])
}
